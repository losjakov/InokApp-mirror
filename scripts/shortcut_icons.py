#!/usr/bin/env python3
"""cloud_41 (A-133 C1): the Android quick-action icons from the SAME glyphs as the tab bar (ionicons outline + the app's church,
src/components/icons.ts) - ONE source (A-15). Writes android/app/src/main/res/drawable/ic_shortcut_<id>.xml (adaptive icon: a white
background, the brand-blue glyph in the safe zone) + ic_shortcut_<id>_fg.xml (the vector). Run: python3 -I scripts/shortcut_icons.py
[--check]  (--check = exit 1 if the files on disk differ: the unit / preflight keep them in step)."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'android/app/src/main/res/drawable')
BLUE = '#FF0C6486'
GLYPH_DP = 40.0          # the glyph inside the 108 dp adaptive canvas (the safe zone is the inner 66 dp)
SCALE = GLYPH_DP / 512.0
SHIFT = (108.0 - GLYPH_DP) / 2.0

def svg_paths(svg):
    """(d, filled?) of every <path> of an ionicons outline SVG"""
    out = []
    for m in re.finditer(r'<path ([^>]*?)/?>', svg):
        a = m.group(1)
        d = re.search(r'\bd="([^"]+)"', a).group(1)
        out.append((d, 'fill="none"' not in a and 'stroke=' not in a))
    return out

def church():
    src = open(os.path.join(ROOT, 'src/components/icons.ts'), encoding='utf-8').read()
    body = src[src.index('export const churchOutline'):]
    body = body[:body.index(');')]
    return [(d, False) for d in re.findall(r'd="([^"]+)"', body)]

def ion(name):
    return svg_paths(open(os.path.join(ROOT, 'node_modules/ionicons/dist/svg', name + '.svg'), encoding='utf-8').read())

# the four quick actions, in the owner's order (A-133): id -> glyph (the tab's own)
ICONS = [('streams', lambda: ion('videocam-outline')), ('monasteries', church), ('map', lambda: ion('map-outline')), ('articles', lambda: ion('newspaper-outline'))]

def fg(paths):
    p = []
    for d, filled in paths:
        if filled:
            p.append(f'        <path android:fillColor="{BLUE}" android:pathData="{d}" />')
        else:
            p.append(f'        <path android:strokeColor="{BLUE}" android:strokeWidth="32" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by scripts/shortcut_icons.py (cloud_41, A-133) - the tab\'s own glyph; do not edit by hand -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f'    <group android:translateX="{SHIFT:g}" android:translateY="{SHIFT:g}" android:scaleX="{SCALE:g}" android:scaleY="{SCALE:g}">\n'
            + '\n'.join(p) + '\n    </group>\n</vector>\n')

def adaptive(i):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by scripts/shortcut_icons.py (cloud_41, A-133): the launcher masks it like every app shortcut -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@android:color/white" />\n'
            f'    <foreground android:drawable="@drawable/ic_shortcut_{i}_fg" />\n</adaptive-icon>\n')

def files():
    out = {}
    for i, g in ICONS:
        out[f'ic_shortcut_{i}_fg.xml'] = fg(g())
        out[f'ic_shortcut_{i}.xml'] = adaptive(i)
    return out

if __name__ == '__main__':
    check = '--check' in sys.argv
    bad = []
    for n, txt in files().items():
        p = os.path.join(RES, n)
        if check:
            if not os.path.exists(p) or open(p, encoding='utf-8').read() != txt: bad.append(n)
        else:
            open(p, 'w', encoding='utf-8').write(txt)
    if check:
        print('shortcut icons: ' + ('PASS' if not bad else 'STALE ' + ', '.join(bad)))
        sys.exit(1 if bad else 0)
    print('shortcut icons written: %d files' % len(files()))
