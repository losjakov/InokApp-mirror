#!/usr/bin/env python3
"""widget_samples.py - 1.0.18 (A-160 / A-163): the widget PICKER samples of Android 12-14 (`android:previewLayout`), generated from THE sample
texts of the CD kit (reports/mockups/a1018/widgets/sample_data.json, copied as android/app/src/main/res/raw/widget_samples.json - the same file
the Android 15+ generated preview (WidgetSamples.java) and the iPhone gallery (ios/App/InokWidgets/widget_samples.json) read) and from the
widgets' OWN row layouts (res/layout/widget_row_<kind>.xml inside widget_list.xml) - one source for the look, one for the words.
  python3 scripts/widget_samples.py          -> writes res/values{,-uk,-ru}/widget_samples.xml + res/layout/widget_preview_<kind>.xml
  python3 scripts/widget_samples.py --check  -> exit 1 if a written file differs from what the sources give (unit widgetSamples)
The kit's 4x2 rows: live 3, upcoming 3, new 4 (README «Rows shown in the references»).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / 'android/app/src/main/res'
DATA = RES / 'raw/widget_samples.json'
ROWS = {'live': 3, 'upcoming': 3, 'new': 4}
FOLDER = {'en': 'values', 'uk': 'values-uk', 'ru': 'values-ru'}  # values/ = English, as the app's other resources
KIND = {'news': 'news', 'pub': 'pub', 'video': 'video'}
NOTE = '<!-- GENERATED by scripts/widget_samples.py from res/raw/widget_samples.json (the CD kit) - do not edit by hand -->\n'


def esc(s: str) -> str:
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    return '\\' + s if s[:1] in ('@', '?') else s


def strings(d: dict) -> str:
    out = []
    add = lambda k, v, raw=False: out.append(f'    <string name="wsample_{k}">{v if raw else esc(v)}</string>')
    add('live_head', f"{d['live_head']} · {d['live_total']}")
    for i, c in enumerate(d['live'][:ROWS['live']], 1): add(f'live_{i}', c['name'])
    add('live_more', d['more_fmt'].replace('{n}', str(d['live_total'] - ROWS['live'])))
    add('up_head', d['up_title'])
    for i, u in enumerate(d['up'][:ROWS['upcoming']], 1):
        # the time is transparent in the text and drawn over it in the accent colour (widget_row_upcoming.xml: both follow the theme)
        add(f'up_{i}', f'<font fgcolor="#00000000">{esc(u["when"])}</font> · {esc(u["name"])}', raw=True)
        add(f'up_time_{i}', u['when'])
    add('new_head', d['new_title'])
    for i, n in enumerate(d['new'][:ROWS['new']], 1): add(f'new_{i}', n['title'])
    return '<?xml version="1.0" encoding="utf-8"?>\n' + NOTE + '<resources>\n' + '\n'.join(out) + '\n</resources>\n'


def body(xml: str) -> str:
    """the element of a layout file without its XML declaration, comments and namespace declaration"""
    xml = re.sub(r'<\?xml[^>]*\?>\s*', '', xml)
    xml = re.sub(r'<!--[\s\S]*?-->\s*', '', xml)
    return xml.replace(' xmlns:android="http://schemas.android.com/apk/res/android"', '').strip()


def set_attr(xml: str, view_id: str, attrs: str) -> str:
    """adds attributes to the view with that id and drops the id (a preview has no ids)"""
    return xml.replace(f'android:id="@+id/{view_id}"', attrs)


def row(kind: str, i: int, d: dict) -> str:
    x = body((RES / f'layout/widget_row_{kind}.xml').read_text(encoding='utf-8'))
    x = x.replace('android:id="@+id/w_row" ', '').replace(' android:src="@mipmap/ic_launcher_round"', '')  # the sample's own picture below
    if kind == 'live':
        x = set_attr(x, 'w_img', f'android:src="@drawable/widget_av_{d["live"][i - 1]["id"]}"')
        x = set_attr(x, 'w_mark', '').replace('<ImageView  ', '<ImageView ')
        x = set_attr(x, 'w_text', f'android:text="@string/wsample_live_{i}"')
    elif kind == 'upcoming':
        x = set_attr(x, 'w_img', f'android:src="@drawable/widget_av_{d["up"][i - 1]["id"]}"')
        x = set_attr(x, 'w_text', f'android:text="@string/wsample_up_{i}"')
        x = set_attr(x, 'w_time', f'android:text="@string/wsample_up_time_{i}"')
        x = re.sub(r'\s*<ImageView android:id="@\+id/w_bell"[^>]*/>', '', set_attr(x, 'w_bell', 'android:id="@+id/w_bell"'))
    else:
        dot = KIND[d['new'][i - 1]['kind']]
        x = set_attr(x, 'w_dot', '').replace('android:src="@drawable/widget_dot_news"', f'android:src="@drawable/widget_dot_{dot}"', 1)
        x = set_attr(x, 'w_text', f'android:text="@string/wsample_new_{i}"')
    x = re.sub(r'<(\w+)\s+android:', r'<\1 android:', x)
    return '\n'.join('        ' + l if l.strip() else l for l in x.split('\n'))


def preview(kind: str, d: dict) -> str:
    x = (RES / 'layout/widget_list.xml').read_text(encoding='utf-8')
    x = re.sub(r'<!--[\s\S]*?-->\n', '', x, count=1)
    head = {'live': 'live_head', 'upcoming': 'up_head', 'new': 'new_head'}[kind]
    x = x.replace('android:id="@+id/w_root" ', '')
    x = x.replace('android:id="@+id/w_header" ', f'android:text="@string/wsample_{head}" ')
    x = x.replace('<ImageView android:id="@+id/w_live_dot" ', '<ImageView ')
    if kind == 'live': x = x.replace('android:src="@drawable/widget_dot" android:visibility="gone"', 'android:src="@drawable/widget_dot"')
    else: x = re.sub(r'\s*<ImageView android:layout_width="8dp"[^>]*widget_dot"[^>]*/>', '', x)
    x = re.sub(r'\s*<TextView android:id="@\+id/w_updated"[^>]*/>', '', x)  # no «оновлено» in a sample (A-163)
    x = re.sub(r'\s*<TextView android:id="@\+id/w_note"[^>]*/>', '', x)
    rows = '\n'.join(row(kind, i, d) for i in range(1, ROWS[kind] + 1))
    x = re.sub(r'<LinearLayout android:id="@\+id/w_rows" ([^>]*)/>', lambda m: f'<LinearLayout {m[1]}>\n{rows}\n    </LinearLayout>', x)
    if kind == 'live':
        x = x.replace('android:id="@+id/w_foot" ', 'android:text="@string/wsample_live_more" ').replace('android:textSize="11sp" android:visibility="gone" />', 'android:textSize="11sp" />')
    else: x = re.sub(r'\s*<TextView android:id="@\+id/w_foot"[^>]*/>', '', x)
    x = x.replace('<?xml version="1.0" encoding="utf-8"?>\n', '<?xml version="1.0" encoding="utf-8"?>\n' + NOTE.replace('-->', f'- the {kind} picker sample (Android 12-14) -->'), 1)
    assert '@+id/' not in x, f'an id left in the {kind} preview'
    return x


def outputs() -> dict:
    data = json.loads(DATA.read_text(encoding='utf-8'))
    out = {RES / f'{FOLDER[l]}/widget_samples.xml': strings(data[l]) for l in FOLDER}
    out.update({RES / f'layout/widget_preview_{k}.xml': preview(k, data['uk']) for k in ROWS})
    return out


if __name__ == '__main__':
    bad = []
    for p, text in outputs().items():
        if '--check' in sys.argv:
            if not p.is_file() or p.read_text(encoding='utf-8') != text: bad.append(str(p.relative_to(ROOT)))
        else: p.write_text(text, encoding='utf-8')
    if bad: raise SystemExit('widget samples out of date: ' + ', '.join(bad) + ' - run python3 scripts/widget_samples.py')
    print('widget samples: ' + ('up to date' if '--check' in sys.argv else 'written') + f' ({len(outputs())} files)')
